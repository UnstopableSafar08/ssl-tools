/**
 * ZIP Module - File bundling and download using JSZip
 */

const Zip = (function() {
    'use strict';

    /**
     * Download a file
     */
    function downloadFile(content, filename, mimeType = 'application/octet-stream') {
        const blob = new Blob([content], { type: mimeType });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = filename;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        URL.revokeObjectURL(url);
    }

    /**
     * Download a PEM file
     */
    function downloadPEM(pemContent, filename) {
        downloadFile(pemContent, filename, 'application/x-pem-file');
    }

    /**
     * Download binary file
     */
    function downloadBinary(binaryContent, filename, mimeType = 'application/octet-stream') {
        const blob = new Blob([binaryContent], { type: mimeType });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = filename;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        URL.revokeObjectURL(url);
    }

    /**
     * Create a ZIP bundle with all artifacts
     */
    async function createBundle(caPemCert, caPemKey, certPemCert, certPemKey, certPemCSR, domain) {
        const zip = new JSZip();

        // Add CA files
        if (caPemCert) {
            zip.file('ca.crt', caPemCert);
        }
        if (caPemKey) {
            zip.file('ca.key', caPemKey);
        }

        // Add certificate files
        if (certPemCert) {
            zip.file(`${domain}.crt`, certPemCert);
        }
        if (certPemKey) {
            zip.file(`${domain}.key`, certPemKey);
        }
        if (certPemCSR) {
            zip.file(`${domain}.csr`, certPemCSR);
        }

        // Add README
        const readme = `# SSL Certificate Bundle

Generated by SSL Certificate Generator

## Files

- ca.crt: Root CA certificate
- ca.key: Root CA private key (KEEP SECRET!)
- ${domain}.crt: Server certificate
- ${domain}.key: Server private key (KEEP SECRET!)
${certPemCSR ? `- ${domain}.csr: Certificate Signing Request\n` : ''}

## Security Notes

- Keep private keys (.key files) secure and never share them
- These certificates are for development/testing only
- Not publicly trusted by browsers
- No revocation (CRL/OCSP) support

## Usage

### Nginx
\`\`\`
ssl_certificate /path/to/${domain}.crt;
ssl_certificate_key /path/to/${domain}.key;
\`\`\`

### Apache
\`\`\`
SSLCertificateFile /path/to/${domain}.crt
SSLCertificateKeyFile /path/to/${domain}.key
\`\`\`

### Kubernetes
See the DevOps Export panel for ready-to-use YAML.
`;
        zip.file('README.txt', readme);

        return zip;
    }

    /**
     * Download ZIP bundle
     */
    async function downloadBundle(caPemCert, caPemKey, certPemCert, certPemKey, certPemCSR, domain) {
        const zip = await createBundle(caPemCert, caPemKey, certPemCert, certPemKey, certPemCSR, domain);
        const content = await zip.generateAsync({ type: 'blob' });
        downloadFile(content, `${domain}-bundle.zip`, 'application/zip');
    }

    /**
     * Get ZIP as base64 for email attachment
     */
    async function getBundleAsBase64(caPemCert, caPemKey, certPemCert, certPemKey, certPemCSR, domain) {
        const zip = await createBundle(caPemCert, caPemKey, certPemCert, certPemKey, certPemCSR, domain);
        const content = await zip.generateAsync({ type: 'base64' });
        return content;
    }

    /**
     * Copy text to clipboard
     */
    async function copyToClipboard(text) {
        try {
            await navigator.clipboard.writeText(text);
            return true;
        } catch (err) {
            return false;
        }
    }

    /**
     * Convert string to base64
     */
    function stringToBase64(str) {
        return btoa(str);
    }

    /**
     * Convert base64 to string
     */
    function base64ToString(base64) {
        return atob(base64);
    }

    return {
        downloadFile,
        downloadPEM,
        downloadBinary,
        createBundle,
        downloadBundle,
        getBundleAsBase64,
        copyToClipboard,
        stringToBase64,
        base64ToString
    };
})();
